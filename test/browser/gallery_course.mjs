import assert from 'node:assert/strict'
import {mkdir,writeFile} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const out=process.env.WITNESS_DIR || 'docs/visual-witnesses/gallery-course-v8'
await mkdir(out,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']})
try {
  const page=await browser.newPage({viewport:{width:1500,height:1100}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:4001/experiments/architecture')
  await page.waitForSelector('.phx-connected')
  await page.waitForSelector('#crossing-rehearsal[data-ready="true"]')
  const root=page.locator('#co-building'),glyph=page.locator('#cb-letter-R')
  const standing=await root.getAttribute('data-standing-digest'),source=await glyph.getAttribute('data-source-hash')
  const click=async id=>{if(id.startsWith('#cb-inspect-'))await page.locator('#cb-listing').evaluate(el=>el.open=true);const r=await root.getAttribute('data-revision');await page.locator(id).click();await page.waitForFunction(v=>document.querySelector('#co-building').dataset.revision!==v,r)}
  const setting=async(key,value)=>{
    const r=await root.getAttribute('data-revision')
    if(['view','layer'].includes(key))await page.selectOption('#cb-'+key,value)
    else await page.locator('#cb-'+key).evaluate((el,val)=>{el.value=val;el.dispatchEvent(new Event('input',{bubbles:true}))},value)
    await page.waitForFunction(v=>document.querySelector('#co-building').dataset.revision!==v,r)
  }
  const screenshot=async n=>root.screenshot({path:`${out}/${n}.png`})
  await screenshot('01-assembled-reference')
  await click('#cb-view-flat')
  const original=JSON.parse(await glyph.getAttribute('data-world'))
  await screenshot('02-flat-one-R')
  await setting('door','22.5');await click('#cb-park_door')
  const mid=JSON.parse(await glyph.getAttribute('data-world'))
  assert.ok(mid.every((p,i)=>Math.abs(p[1]-original[i][1])<1e-9))
  assert.ok(mid.some((p,i)=>p[2]>original[i][2]+0.01))
  await screenshot('03-intermediate-door')
  await setting('door','90')
  assert.equal(await glyph.getAttribute('data-visibility'),'edge_on')
  assert.equal(await glyph.locator('polygon').count(),0)
  await click('#cb-restore_door')
  assert.equal(await root.getAttribute('data-door'),'22.5')
  assert.equal(await glyph.getAttribute('data-source-hash'),source)
  await page.locator('#cb-trace').click();await page.waitForFunction(()=>document.querySelector('#cb-letter-status').textContent.includes('tracing true'))
  await click('#cb-R-road');await click('#cb-view-transverse');await click('#cb-stitch')
  assert.equal(await page.locator('#cb-letter-R').count(),1)
  assert.equal(await glyph.getAttribute('data-source-hash'),source)
  assert.match(await page.locator('#cb-letter-status').innerText(),/actual stitching false/)
  await screenshot('04-road-stitching-rehearsal')
  await page.locator('#cb-listing').evaluate(el=>el.open=true)
  await click('#cb-inspect-cb-wedge-A')
  await click('#cb-isolate')
  assert.equal(await page.locator('.cb-inspector').getAttribute('data-selected'),'cb:wedge-A')
  await screenshot('05-isolated-wedge')
  await click('#cb-reveal')
  await click('#cb-inspect-cb-segmentation');await click('#cb-isolate');await setting('wedge','90')
  assert.equal(await page.locator('#cb-fold-collision').count(),1)
  await screenshot('05b-fold-interference')
  await setting('wedge','0');await click('#cb-reveal');await click('#cb-inspect-cb-wedge-A')
  await setting('layer','0')
  assert.equal(await page.locator('.cb-inspector').getAttribute('data-selected'),'cb:wedge-A')
  await setting('layer','5')
  await click('#cb-view-tunneling');await click('#cb-M-projection')
  await screenshot('06-seat-gallery-return')
  assert.equal(await root.getAttribute('data-standing-digest'),standing)
  assert.equal(await root.getAttribute('data-acquired-delta'),'0')
  for(let n=1;n<=7;n++) {
    await click('#cb-course-stage-'+n)
    if(n===1) assert.notEqual(await glyph.getAttribute('data-visibility'),'edge_on')
    if(n===2) {assert.equal(await glyph.getAttribute('data-visibility'),'edge_on');assert.equal(await glyph.locator('polygon').count(),0)}
    if(n>=3) await click('#cb-view-side')
    await screenshot('course-'+n)
    assert.equal(await glyph.getAttribute('data-source-hash'),source)
    assert.equal(await root.getAttribute('data-standing-digest'),standing)
  }
  await click('#cb-course-stage-3')
  for(const view of ['flat','side','tunneling-under']) {
    await click('#cb-view-'+view)
    assert.ok(await page.locator('polygon[data-part="cb:under-curve"]').count()>0)
    await screenshot('undercurve-'+view)
  }
  await click('#cb-course-stage-6');await click('#cb-view-oblique');await screenshot('complete-prospective-course')
  await click('#cb-course-stage-7')
  assert.match(await page.locator('#cb-selected-name').innerText(),/FLAT/)
  assert.match(await page.locator('#cb-course-clearance').innerText(),/aperture interference: false/)
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await screenshot('07-mobile')
  await page.reload();await page.waitForSelector('#crossing-rehearsal[data-ready="true"]')
  assert.equal(await glyph.getAttribute('data-source-hash'),source)
  assert.equal(await root.getAttribute('data-standing-digest'),standing)
  assert.deepEqual(errors,[])
  await writeFile(`${out}/verification.json`,JSON.stringify({oneRSource:source,standingDigestUnchanged:true,stageDoorChangesDepthNotHeight:true,flatAt90:'edge_on',rInstances:1,stitchingAcquired:false,selectionSurvivesLayers:true,wedgeInterferenceDisclosed:true,referenceRestoredAfterReload:true,seatGallery:true,sevenCourseStages:true,underSeatFlatSideTunneling:true,nextPinningFlat:true,acquisitionDelta:0,legacyRetained:true,mobileOverflow:false,pageErrors:errors},null,2))
  console.log('PASS Gallery course v8: one R, continuous Door, stable source/standing, finite parts, overlays, Seat/Gallery and mobile.')
} finally {await browser.close()}
