import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const out = process.env.PUFFING_WITNESSES || 'docs/visual-witnesses/first-puffing'
await mkdir(out, {recursive:true})
const browser = await chromium.launch({headless:true,args:['--no-sandbox']})
const page = await browser.newPage({viewport:{width:1280,height:1050}})
const errors=[]
page.on('pageerror', e=>errors.push(e.message))
try {
  await page.goto(`${process.env.ZEROETH_URL || 'http://127.0.0.1:4001'}/experiments/architecture`)
  await page.waitForFunction(()=>document.querySelector('#puffing-squeeze')?.disabled===false && location.search.includes('id='))
  const url=page.url()
  assert.equal(await page.locator('#cob-square').count(),1)
  assert.equal(await page.locator('#cob-bobbining').count(),0)
  await page.screenshot({path:`${out}/01-reserved-square.png`,fullPage:true})
  const bulb=await page.locator('#puffing-squeeze').boundingBox()
  await page.mouse.move(bulb.x+bulb.width/2,bulb.y+bulb.height/2)
  await page.mouse.down()
  await page.mouse.move(bulb.x+bulb.width/2,bulb.y+bulb.height/2+20)
  assert.ok(Number(await page.locator('#puffing-squeeze').evaluate(el=>el.style.getPropertyValue('--compression')))>=.65)
  await page.mouse.up()
  await page.locator('#cob-bobbining').waitFor()
  await page.waitForFunction(()=>document.querySelector('#puffing-squeeze').disabled)
  assert.equal(await page.locator('#cob-square').count(),0)
  await page.screenshot({path:`${out}/02-cob-from-within.png`,fullPage:true,animations:'disabled'})
  await page.locator('#cob-bobbining').click()
  await page.locator('#held-reading[data-held-relation=cob-standing]').waitFor()
  await page.screenshot({path:`${out}/03-held-consequence.png`,fullPage:true,animations:'disabled'})
  await page.locator('#follow-predecessor').click()
  await page.locator('#held-reading[data-held-relation=possibility-extent-standing]').waitFor()
  await page.locator('#close-locality').click()
  await page.locator('#appoint-pointingable').click()
  await page.locator('#pointingable-standing').waitFor()
  await page.reload()
  await page.locator('#cob-bobbining').waitFor()
  await page.locator('#pointingable-standing').waitFor()
  assert.equal(page.url(),url)
  assert.equal(await page.locator('#puffing-squeeze').isDisabled(),true)
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:`${out}/04-mobile.png`,fullPage:true,animations:'disabled'})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto(`${process.env.ZEROETH_URL || 'http://127.0.0.1:4001'}/experiments/architecture`)
  await page.waitForFunction(()=>document.querySelector('#puffing-squeeze')?.disabled===false && location.search.includes('id='))
  await page.locator('#puffing-squeeze').focus()
  await page.keyboard.press('Enter')
  await page.locator('#cob-bobbining').waitFor()
  assert.equal(await page.locator('#cob-bobbining .cob-body').evaluate(el=>getComputedStyle(el).animationName),'none')
  assert.deepEqual(errors,[])
  console.log('PASS: compression; square→COB persisted; local provenance; pointing appointment; UUID reload; mobile; keyboard/reduced-motion; no browser errors')
} finally { await browser.close() }
