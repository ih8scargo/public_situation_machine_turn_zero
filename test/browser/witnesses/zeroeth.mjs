import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base=process.env.ZEROETH_URL || 'http://127.0.0.1:4001'
const out=process.env.ZEROETH_WITNESSES || 'docs/visual-witnesses'
await mkdir(out,{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1280,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
try {
  await page.goto(`${base}/experiments/architecture`)
  await page.locator('#center-square').waitFor()
  await page.waitForFunction(()=>document.querySelector('#ring-purchase').dataset.disabled==='false')
  await page.evaluate(()=>{
    window.squareWitness=document.querySelector('#center-square')
    window.chainWitness=document.querySelector('#cob-chain-segment-1')
    window.materialWitness=document.querySelector('#fountaining-character-0')
  })
  const initialURL=page.url()
  const ring=await page.locator('#pulling-ring').boundingBox()
  // A real click is not accomplished pulling labor.
  await page.mouse.click(ring.x+ring.width/2,ring.y+ring.height/2)
  await page.waitForFunction(()=>document.querySelector('#ring-purchase').dataset.pulling!=='true')
  assert.equal(await page.locator('#pull-readout').count(),0)
  await page.screenshot({path:`${out}/zeroeth-approach.png`,fullPage:true})
  await page.mouse.move(ring.x+ring.width/2,ring.y+ring.height/2)
  await page.mouse.down();await page.mouse.move(ring.x+ring.width/2+90,ring.y+ring.height/2+25,{steps:12});await page.mouse.up()
  await page.locator('#pull-readout').waitFor()
  await page.waitForFunction(()=>document.querySelector('.constitutional-world').dataset.bearing==='situated')
  assert.equal(await page.evaluate(()=>window.squareWitness===document.querySelector('#center-square')),true)
  assert.equal(await page.evaluate(()=>window.materialWitness===document.querySelector('#fountaining-character-0')),true)
  await page.evaluate(()=>{window.bendCharacter=document.querySelector('#fountaining-character-5')})
  await page.waitForFunction(()=>Number(document.querySelector('#fountaining-character-5').dataset.courseParameter)>0.65)
  assert.equal(await page.evaluate(()=>window.bendCharacter===document.querySelector('#fountaining-character-5')),true)
  await page.locator('#fountaining-character-0').evaluate(el=>el.click())
  await page.waitForFunction(()=>document.querySelector('#fountaining-character-0').dataset.held==='true')
  await page.screenshot({path:`${out}/zeroeth-cubical-situated.png`,fullPage:true,animations:'disabled'})
  await page.locator('#regard-end-on').click()
  await page.waitForFunction(()=>document.querySelector('.constitutional-world').dataset.bearing==='end-on')
  assert.equal(await page.evaluate(()=>window.materialWitness===document.querySelector('#fountaining-character-0')),true)
  await page.screenshot({path:`${out}/zeroeth-fountain-end-on.png`,fullPage:true,animations:'disabled'})
  await page.locator('#regard-situated').click()
  await page.waitForFunction(()=>document.querySelector('.constitutional-world').dataset.bearing==='situated')
  await page.locator('#dismiss-pull-readout').click();await page.locator('#pull-readout').waitFor({state:'detached'})
  await page.locator('#return-pull-readout').click();await page.locator('#pull-readout').waitFor()
  // Keyboard accommodation witnesses both ordered purchases; it never auto-snaps geometry.
  await page.locator('#feed-stick').focus();await page.keyboard.press('Space');await page.keyboard.press('r');await page.keyboard.press('c')
  for(let n=1;n<=3;n++){await page.keyboard.press('ArrowUp');await page.waitForFunction(n=>document.querySelector('#spindle')?.dataset.extent===String(n),n)}
  assert.equal(await page.evaluate(()=>window.squareWitness===document.querySelector('#center-square')),true)
  assert.equal(await page.evaluate(()=>window.chainWitness===document.querySelector('#cob-chain-segment-1')),true)
  await page.screenshot({path:`${out}/zeroeth-spindle-during.png`,fullPage:true,animations:'disabled'})
  for(let n=4;n<=6;n++){await page.keyboard.press('ArrowUp');await page.waitForFunction(n=>document.querySelector('#spindle')?.dataset.extent===String(n),n)}
  await page.locator('#pointingable-standing').waitFor()
  assert.equal(await page.evaluate(()=>window.squareWitness===document.querySelector('#center-square')),true)
  assert.equal(await page.evaluate(()=>window.chainWitness===document.querySelector('#cob-chain-segment-1')),true)
  assert.equal(await page.evaluate(()=>window.materialWitness===document.querySelector('#fountaining-character-0')),true)
  await page.screenshot({path:`${out}/zeroeth-pointingable.png`,fullPage:true,animations:'disabled'})
  await page.reload();await page.locator('#pointingable-standing').waitFor();assert.equal(page.url(),initialURL)
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:`${out}/zeroeth-mobile.png`,fullPage:true,animations:'disabled'})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true)
  const pointerPage=await browser.newPage({viewport:{width:1280,height:1500}})
  pointerPage.on('pageerror',e=>errors.push(e.message))
  await pointerPage.goto(`${base}/experiments/architecture`)
  await pointerPage.locator('#center-square').waitFor()
  await pointerPage.locator('#pulling-ring').focus();await pointerPage.keyboard.press('Space');await pointerPage.keyboard.press('ArrowRight');await pointerPage.keyboard.press('Space')
  await pointerPage.locator('#feed-stick').waitFor()
  await pointerPage.locator('#feed-stick').scrollIntoViewIfNeeded()
  await pointerPage.evaluate(()=>window.pointerSquare=document.querySelector('#center-square'))
  const handle=await pointerPage.locator('#feed-stick').boundingBox()
  const regarding=await pointerPage.locator('#square-for-regarding').boundingBox()
  const center=await pointerPage.locator('#center-square').boundingBox()
  await pointerPage.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await pointerPage.mouse.down()
  await pointerPage.mouse.move(regarding.x+regarding.width/2,regarding.y+regarding.height/2,{steps:12})
  await pointerPage.mouse.move(center.x+center.width/2,center.y+center.height/2,{steps:20})
  await pointerPage.mouse.move(center.x+center.width/2,center.y+center.height/2-76,{steps:12})
  await pointerPage.waitForFunction(()=>document.querySelector('#spindle')?.dataset.extent==='3')
  await pointerPage.mouse.up()
  assert.equal(await pointerPage.evaluate(()=>window.pointerSquare===document.querySelector('#center-square')),true)
  await pointerPage.screenshot({path:`${out}/zeroeth-pointer-feed.png`,fullPage:true,animations:'disabled'})
  await pointerPage.close()
  assert.deepEqual(errors,[])
  console.log('PASS: actual pull/click distinction, stable square/material/COB DOM identities, both bearings, readout return, finite ordered co-labor, UUID resume, mobile overflow, no browser errors.')
} finally { await browser.close() }
