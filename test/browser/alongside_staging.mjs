import assert from 'node:assert/strict'
import {mkdir,writeFile} from 'node:fs/promises'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const output=process.env.WITNESS_DIR || 'docs/visual-witnesses/alongside-staging-v4'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']})
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:4001/workshop/string-ribbon');await page.waitForSelector('.phx-connected')
 const root=page.locator('#geometry-exploration'),bench=page.locator('#alongside-staging')
 const click=async id=>{const r=Number(await root.getAttribute('data-revision'));await page.locator(id).click();await page.waitForFunction(n=>Number(document.querySelector('#geometry-exploration').dataset.revision)>n,r)}
 const material=(view,id)=>page.locator(`#as-view-${view} g[data-material="${id}"]`)
 const world=(view,id)=>material(view,id).getAttribute('data-world')
 const snap=name=>bench.screenshot({path:`${output}/${name}.png`})
 const inherited=await world('flat','alongside:inherited-reference')
 const aperture=await page.locator('#as-aperture-flat').getAttribute('data-world')
 const B=await page.locator('#ge-scene-current-turn-measure').getAttribute('data-world')
 await snap('01-inherited-reference')
 await click('#as-pivot-30')
 assert.equal(await world('flat','alongside:inherited-reference'),inherited)
 assert.equal(await page.locator('#as-aperture-flat').getAttribute('data-world'),aperture)
 assert.equal(await material('flat','alongside:material-1').count(),0)
 await click('#as-appoint');await click('#as-stage')
 assert.equal(await material('flat','alongside:material-1').getAttribute('data-status'),'newly_staged')
 assert.equal(await material('flat','alongside:material-1').getAttribute('data-acquisition'),'not_acquired')
 assert.equal(await material('flat','alongside:inherited-reference').getAttribute('data-acquisition'),'not_attested')
 const staged=await world('flat','alongside:material-1')
 for(const view of ['flat','transverse','plan'])assert.equal(await world(view,'alongside:material-1'),staged)
 await snap('02-staged-alongside')
 await click('#as-pivot-60')
 assert.equal(await world('flat','alongside:material-1'),staged)
 await snap('03-regarding-only')
 await click('#as-retain')
 assert.equal(await world('flat','alongside:material-1'),staged)
 await click('#as-appoint');await click('#as-stage');await click('#as-retain')
 assert.equal(await bench.getAttribute('data-furnished'),'2')
 assert.match(await page.locator('#as-deflection').innerText(),/30.0/)
 await snap('04-angular-registration-control')
 await click('[id="as-inspect-alongside:material-1"]')
 assert.match(await page.locator('#as-selection').innerText(),/alongside:material-1/)
 await click('#as-acquire');assert.match(await page.locator('#as-notice').innerText(),/human_frame_unacquired/)
 await click('#as-scan');assert.match(await page.locator('#as-notice').innerText(),/landinging_not_acquired/)
 assert.equal(await bench.getAttribute('data-from-down-under'),'false')
 assert.equal(await root.getAttribute('data-index'),'0')
 assert.equal(await page.locator('#ge-diagonal-b-witness').getAttribute('data-next-status'),'not-furnished')
 assert.equal(await page.locator('#ge-scene-current-turn-measure').getAttribute('data-world'),B)
 await snap('05-acquisition-and-work-blocked')
 await page.setViewportSize({width:390,height:844})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await snap('06-mobile')
 assert.deepEqual(errors,[])
 await writeFile(`${output}/verification.json`,JSON.stringify({geometryContract:'geometry-table-2026-11-13.v4',sameMaterialAcrossViews:true,pivotDoesNotMoveMaterial:true,explicitAppointmentAndStage:true,inheritedAcquisition:'not_attested',stagedAcquisition:'not_acquired',candidateFurnishings:2,registrationDeflectionDegrees:30,occupiedAxleCurvature:'unproved',landingAcquisition:'blocked',cobWork:'blocked',fromDownUnderEstablished:false,diagonalBPreserved:true,acquiredIndex:0,pageErrors:errors,mobileOverflow:false},null,2))
 console.log('PASS alongside staging: explicit phases, shared aperture/world, control deflection, blocked acquisition/work and mobile.')
}finally{await browser.close()}
