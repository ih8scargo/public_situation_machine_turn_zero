import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.WITNESS_DIR || '/tmp/psm-coming-aboard-appliance'
await mkdir(output, {recursive: true})
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']})
try {
  const page = await browser.newPage({viewport:{width:1280,height:900}})
  const errors=[]
  page.on('pageerror', e=>errors.push(e.message))
  await page.goto(process.env.COMING_ABOARD_URL || 'http://127.0.0.1:4001/workshop/coming-aboard')
  await page.waitForSelector('.phx-connected')
  await page.waitForSelector('#ca-appliance')
  const squareCheck = async () => {
    for (const id of ['ca-square-0','ca-square-1']) {
      const b=await page.locator('#'+id).boundingBox()
      assert.ok(Math.abs(b.width-b.height)<1, `${id}: ${b.width} × ${b.height}`)
      const square = page.locator('#'+id)
      assert.deepEqual(await square.locator('[data-corner]').allTextContents(), ['XT','YT','YT','XT'])
      assert.deepEqual(await square.locator('[data-edge]').evaluateAll(arrows => arrows.map(arrow => {
        const [tip, left, right] = arrow.getAttribute('points').split(' ').map(point => point.split(',').map(Number))
        const dx = tip[0] - (left[0] + right[0]) / 2
        const dy = tip[1] - (left[1] + right[1]) / 2
        return [arrow.dataset.edge, Math.sign(dx), Math.sign(dy)]
      })), [['top',1,0],['right',0,1],['bottom',-1,0],['left',0,-1]])
      assert.deepEqual(await square.locator('[data-bearing="XT TOWARD YT"]').evaluateAll(diagonals =>
        diagonals.map(diagonal => diagonal.getAttribute('d'))), ['M30 270 L270 30','M30 30 L270 270'])
    }
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  }
  await squareCheck()
  const tabBounds=await page.locator('#pulling-ring').boundingBox()
  assert.ok(tabBounds.width>100 && tabBounds.height>=44)
  assert.equal(await page.locator('#ca-cup-hook').isDisabled(),true)
  const witness = page.locator('#ca-pull-witness')
  const source = await witness.getAttribute('data-here')
  const held = await page.locator('#ca-opening-hold').getAttribute('d')
  assert.equal(await witness.getAttribute('data-opening'),'held')
  assert.equal(await page.locator('#ca-groundward-trace').count(),0)
  assert.equal(await page.locator('#ca-table-center-trace').count(),1)
  assert.match(await page.locator('#ca-table-registration').innerText(), /common extent frame/)
  for (const id of ['ca-standing-string','ca-regarding-string']) {
    await page.locator('#'+id+' summary').click()
    assert.match(await page.locator('#'+id).innerText(), /Groundward|fixed monitor/)
  }
  await witness.screenshot({path:output+'/01-before-pull.png'})
  const tab=page.locator('#pulling-ring')
  await tab.click()
  assert.equal(await witness.getAttribute('data-opening'),'held')
  assert.equal(await page.locator('#ca-groundward-trace').count(),0)
  await tab.focus(); await tab.press('Space'); await tab.press('ArrowRight'); await tab.press('Escape')
  assert.equal(await witness.getAttribute('data-opening'),'held')
  assert.equal(await page.locator('#ca-groundward-trace').count(),0)
  await tab.press('Space'); await tab.press('ArrowUp'); await tab.press('Space')
  await page.waitForSelector('#coming-aboard[data-pose=loosened]')
  assert.equal(await witness.getAttribute('data-opening'),'accepted')
  assert.equal(await witness.getAttribute('data-here'),source)
  assert.notEqual(await page.locator('#ca-opening-hold').getAttribute('d'),held)
  const groundward = page.locator('#ca-groundward-trace')
  assert.equal(await groundward.getAttribute('data-from'), source)
  assert.equal(await groundward.getAttribute('data-return'), source)
  assert.equal(await groundward.getAttribute('data-attachment'), 'registered')
  assert.ok(await groundward.locator('.ca-groundward-return').isVisible())
  await witness.screenshot({path:output+'/01a-after-pull.png'})

  const order = page.locator('#ca-quilling-order')
  await order.locator('summary').click()
  assert.deepEqual(await order.locator('li').evaluateAll(items => items.map(item => item.dataset.role)),
    ['human-quilling','doll-stitching'])
  assert.match(await order.innerText(), /non-agentive/)
  assert.equal(await page.locator('[id^="ca-material-"]').count(),0)

  await page.locator('#ca-view-within-cab').click()
  const horn = page.getByRole('button', {name:'PUFF to inspect the wedging'})
  await horn.press('Enter')
  const inspection = page.locator('#ca-cab-inspection')
  await page.waitForSelector('#ca-cab-inspection[data-inspection=regarding]')
  assert.match(await inspection.getAttribute('data-wedge'), /^partial-ring-/)
  assert.ok(await inspection.locator('canvas').evaluate(canvas => canvas.getContext('2d')
    .getImageData(0, 0, canvas.width, canvas.height).data.some(value => value !== 0)))
  await page.locator('#ca-within-cab').screenshot({path:output+'/01b-within-cab-puff.png'})
  await page.locator('#ca-cab-select').click()
  await page.waitForSelector('#ca-cab-inspection[data-inspection=selected]')
  assert.equal(await page.locator('#ca-inherited-standing').getAttribute('data-acquired'),'false')
  assert.equal(await page.locator('#ca-cob').getAttribute('data-confirmed'),'false')
  assert.equal(await page.locator('#ca-appliance').getAttribute('data-illuminations'),'0')
  await page.locator('#ca-view-flat').click()
  await page.waitForSelector('#ca-room-geometry[data-view=flat]')
  assert.equal(await horn.count(),0)
  await page.locator('#ca-puff').click()
  await page.locator('#ca-cup-hook').click()
  await page.waitForSelector('#ca-telephone[data-line=open]')
  await page.locator('#ca-inquiry-text').fill('Which bearing stands FROM HERE?')
  await page.locator('#ca-send-inquiry').click()
  await page.waitForSelector('#ca-console[data-speaking=true]')
  assert.equal(await page.locator('[id^="ca-material-"]').count(),0)
  // Native button supports keyboard appointment; click witnesses Pointing-able input.
  await page.locator('#ca-door-2').focus(); await page.locator('#ca-door-2').press('Enter')
  await page.waitForSelector('#ca-door-2[aria-pressed=true]')
  await page.locator('#ca-draft-text').fill('PLACEHOLDER · FROM HERE')
  await page.locator('#ca-stage').click()
  await page.waitForSelector('#ca-material-2')
  const material=await page.locator('#ca-material-2').getAttribute('data-material')
  const here=await page.locator('#ca-appliance').getAttribute('data-here')
  await page.locator('#ca-approach').click()
  await page.waitForSelector('#ca-inherited-standing[data-material]')
  for (const id of ['ca-view-dollside','ca-gallery-roundabout','ca-view-tunnel','ca-view-flat','ca-gallery-longhouse','ca-door-7']) {
    await page.locator('#'+id).click()
    await page.waitForSelector('#'+id+'[aria-pressed=true]')
    assert.equal(await page.locator('#ca-inherited-standing').getAttribute('data-material'),material)
    assert.equal(await page.locator('#ca-inherited-standing').getAttribute('data-here'),here)
    assert.equal(await page.locator('#ca-material-2').getAttribute('data-acquired'),'false')
    assert.equal(await page.locator('#ca-appliance').getAttribute('data-illuminations'),'0')
    assert.equal(await witness.getAttribute('data-opening'),'accepted')
    assert.equal(await witness.getAttribute('data-here'),source)
  }
  await page.locator('#ca-view-dollside').click()
  await page.waitForSelector('#ca-regarding-native canvas')
  assert.ok(await page.locator('#ca-regarding-native canvas').evaluate(c=>c.getContext('2d').getImageData(0,0,c.width,c.height).data.some(v=>v!==0)))
  await page.screenshot({path:output+'/02-dollside.png',fullPage:true})
  await page.locator('#ca-view-flat').click()
  await page.locator('#ca-cup-hook').click()
  await page.waitForSelector('#ca-console[data-speaking=false]')
  assert.equal(await page.locator('#ca-send-inquiry').isDisabled(),true)
  await page.locator('#ca-provisional-fittings summary').click()
  await page.locator('#config_bugs').selectOption('3')
  await page.locator('#config_restep').selectOption('12')
  await page.waitForFunction(()=>document.querySelector('#ca-config-status').textContent.includes('Bugs 3 · RE-STEP 12'))
  assert.equal(await page.locator('#ca-appliance').getAttribute('data-illuminations'),'0')
  await page.locator('#ca-provisional-fittings summary').click()
  await page.screenshot({path:output+'/03-staged-approached.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.emulateMedia({reducedMotion:'reduce'})
  await squareCheck()
  await page.screenshot({path:output+'/04-mobile.png',fullPage:true})
  const second=await browser.newPage({viewport:{width:390,height:844}})
  await second.goto(page.url())
  await second.waitForSelector('.phx-connected')
  assert.notEqual(await second.locator('#ca-appliance').getAttribute('data-here'),here)
  assert.equal(await second.locator('[id^="ca-material-"]').count(),0)
  await second.locator('#ca-view-within-cab').click()
  const mobileHorn = second.getByRole('button', {name:'PUFF to inspect the wedging'})
  assert.ok(await mobileHorn.isDisabled())
  const mobileTab = second.locator('#pulling-ring')
  await mobileTab.press('Space'); await mobileTab.press('ArrowUp'); await mobileTab.press('Space')
  await second.waitForSelector('#ca-groundward-trace')
  await mobileHorn.click()
  await second.waitForSelector('#ca-cab-inspection[data-inspection=regarding]')
  assert.ok(await second.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await second.locator('#ca-within-cab').screenshot({path:output+'/05-mobile-within-cab.png'})
  assert.deepEqual(errors,[])
  console.log('Appliance browser checks passed at 1280×900 and 390×844. Screenshots: '+output)
} finally { await browser.close() }
